/* Страница правил.

   Своего кода тут почти нет: нужно только применить язык и тему, чтобы
   страница не выбивалась из остального сайта. Вход не требуется —
   правила читают до того, как заходят. */
(function () {
  'use strict';
  var A = window.App;

  /* Оформление берём из настроек, если человек уже вошёл. Не вошёл —
     остаётся то, что записано в разметке, и страница всё равно
     выглядит как сайт, а не как голый текст.

     Раньше здесь стоял один loadMe(): тема применялась, а язык — нет.
     Посетитель, выбравший английский (в настройках или кнопкой на
     другой странице), открывал правила и читал их по-русски, хотя
     английский текст лежит в разметке рядом. boot делает то же, что на
     остальных страницах: берёт язык из настроек аккаунта, иначе из
     браузера, и применяет его. Пускать после входа тут некуда — поэтому
     без продолжения. */
  A.boot();
}());
